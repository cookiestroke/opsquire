"""Generated docs: a catalog of everything in the home and an API page per general script, built from code
(module/function docstrings and signatures), tests (what the code guarantees), meta.json and run records.
Agents read these before opening code; nothing here is edited by hand."""

from __future__ import annotations

import ast
import re
from pathlib import Path
from typing import Any

from .model import Task, all_task_folders, home_dir, load_task, write_text
from .query import runs_for, task_status

HEADER = "<!-- generated by `opsquire docs`; do not edit, regenerate instead -->\n"


def docs_dir() -> Path:
    return home_dir() / "docs"


def first_line(doc: str | None) -> str:
    return (doc or "").strip().split("\n\n")[0].replace("\n", " ").strip()


def signature(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{fn.name}({ast.unparse(fn.args)}){ret}"


def module_api(path: Path) -> dict[str, Any]:
    try:
        tree = ast.parse(path.read_text())
    except (OSError, SyntaxError) as e:
        return {"doc": f"(unparseable: {type(e).__name__})", "functions": [], "classes": []}
    functions = [
        (signature(n), first_line(ast.get_docstring(n)))
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")
    ]
    classes = []
    for n in tree.body:
        if isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
            methods = [
                (signature(m), first_line(ast.get_docstring(m)))
                for m in n.body
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and not m.name.startswith("_")
            ]
            classes.append((n.name, first_line(ast.get_docstring(n)), methods))
    return {"doc": (ast.get_docstring(tree) or "").strip(), "functions": functions, "classes": classes}


def guarantees(path: Path) -> list[str]:
    """Test names as plain sentences: what the tests check."""
    try:
        tree = ast.parse(path.read_text())
    except (OSError, SyntaxError):
        return []
    out = []
    for cls in tree.body:
        if isinstance(cls, ast.ClassDef):
            for m in cls.body:
                if isinstance(m, ast.FunctionDef) and m.name.startswith("test_"):
                    out.append(f"{cls.name}: {m.name[5:].replace('_', ' ')}")
    return out


def usage(task: Task, tasks: list[Task]) -> dict[str, Any]:
    users = [t.id for t in tasks if t.meta and task.id in t.meta.uses]
    runs = [r for tid in [task.id, *users] for r in runs_for(tid)]
    ok = sum(1 for r in runs if r.get("status") == "ok")
    last = max((str(r.get("started")) for r in runs), default="")
    return {"users": users, "runs": len(runs), "ok": ok, "last_run": last}


def api_page(task: Task, tasks: list[Task]) -> str:
    meta = task.raw
    u = usage(task, tasks)
    lines = [HEADER, f"# {task.id}\n", f"{meta.get('purpose', '')}\n"]
    targets = ", ".join(meta.get("targets") or [])
    lines.append(f"- kind: {task.kind}; changes prod: {meta.get('changes_prod')}; targets: {targets}")
    lines.append(f"- used by: {', '.join(u['users']) or 'nothing yet'}")
    lines.append(f"- runs (it and its users): {u['runs']}, ok {u['ok']}, last {u['last_run'] or 'never'}\n")
    code = sorted(p for p in task.folder.glob("*.py") if not p.name.startswith("test_"))
    for path in code:
        api = module_api(path)
        lines.append(f"## {path.name}\n")
        if api["doc"]:
            lines.append(api["doc"] + "\n")
        for sig, doc in api["functions"]:
            lines.append(f"- `{sig}`" + (f": {doc}" if doc else ""))
        for name, doc, methods in api["classes"]:
            lines.append(f"- class `{name}`" + (f": {doc}" if doc else ""))
            lines += [f"  - `{sig}`" + (f": {d}" if d else "") for sig, d in methods]
        lines.append("")
    checks = [g for p in sorted(task.folder.glob("test_*.py")) for g in guarantees(p)]
    lines.append("## What the tests guarantee\n")
    lines += [f"- {g}" for g in checks] or ["- (no tests)"]
    return "\n".join(lines) + "\n"


def catalog(tasks: list[Task]) -> str:
    rows = [HEADER, "# Opsquire catalog\n", "Read this before opening code. Reuse before writing anything new.\n"]
    general = [t for t in tasks if t.kind == "general"]
    rows.append("## General scripts (reusable)\n")
    for t in general:
        u = usage(t, tasks)
        tests = sum(len(guarantees(p)) for p in t.folder.glob("test_*.py"))
        rows.append(
            f"- **{t.id}**: {t.raw.get('purpose', '')} "
            f"(tests: {tests}; used by {len(u['users'])}; runs {u['runs']}, ok {u['ok']}) -> docs/{t.id}.md"
        )
    if not general:
        rows.append("- (none yet)")
    rows.append("\n## Tasks and plans\n")
    for t in tasks:
        if t.kind == "general":
            continue
        uses = t.raw.get("uses") or []
        extra = f" (uses {', '.join(uses)})" if uses else ""
        rows.append(f"- {t.id} [{task_status(t, runs_for(t.id))}, {t.kind}]: {t.raw.get('purpose', '')}{extra}")
    return "\n".join(rows) + "\n"


def write_docs() -> Path:
    tasks = [load_task(f) for f in all_task_folders()]
    out = docs_dir()
    out.mkdir(exist_ok=True)
    wanted = {"CATALOG.md"}
    write_text(out / "CATALOG.md", catalog(tasks))
    for t in tasks:
        if t.kind == "general":
            wanted.add(f"{t.id}.md")
            write_text(out / f"{t.id}.md", api_page(t, tasks))
    for stale in out.glob("*.md"):
        if stale.name not in wanted and re.match(r"^[a-z0-9_.-]+\.md$", stale.name):
            stale.unlink()
    return out
